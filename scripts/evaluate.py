"""Evaluate saved predictions, generate traceable tables and regenerate all figures offline."""

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from PIL import Image

from beanleaf.core import CLASSES, metrics, write_json


NAMES = {
    "color": "Color + logistic regression",
    "resnet18_frozen": "Frozen ResNet-18 + logistic regression",
    "resnet18_partial_finetune": "Partial fine-tune, one epoch + augmentation",
}


def wilson(successes, trials):
    """95% Wilson binomial interval, conditional on this trained model and split."""
    if trials == 0:
        return [None, None]
    z = 1.959963984540054
    p = successes / trials
    denominator = 1 + z * z / trials
    center = (p + z * z / (2 * trials)) / denominator
    radius = z * np.sqrt(p * (1 - p) / trials + z * z / (4 * trials * trials)) / denominator
    return [max(0.0, float(center - radius)), min(1.0, float(center + radius))]


def per_class(y_true, y_pred):
    result = {}
    for index, name in enumerate(CLASSES):
        tp = int(np.sum((y_true == index) & (y_pred == index)))
        predicted = int(np.sum(y_pred == index))
        support = int(np.sum(y_true == index))
        result[name] = {
            "support": support,
            "predicted_positive": predicted,
            "precision": tp / predicted if predicted else 0.0,
            "precision_95ci": wilson(tp, predicted),
            "recall": tp / support if support else 0.0,
            "recall_95ci": wilson(tp, support),
        }
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--reports", type=Path, default=Path("reports"))
    args = parser.parse_args()
    folder = args.reports
    predictions = json.loads((folder / "predictions.json").read_text())
    recorded = json.loads((folder / "metrics.json").read_text())
    truth = np.array(predictions["y_true"])
    evaluated = {}
    rows = [
        "# Measured results",
        "",
        "Generated by `scripts/evaluate.py` from saved predictions.",
        "",
        "| Model | Correct | Accuracy | Macro F1 |",
        "|---|---:|---:|---:|",
    ]
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.7), layout="constrained")
    for ax, (name, title) in zip(axes, NAMES.items()):
        pred = np.array(predictions[name]["predicted"])
        score = metrics(truth, pred)
        if score != recorded["models"][name]["test"]:
            raise ValueError(f"Saved metrics disagree with predictions: {name}")
        score["accuracy_95ci"] = wilson(score["correct"], score["n"])
        score["per_class"] = per_class(truth, pred)
        evaluated[name] = score
        rows.append(
            f"| {title} | {score['correct']}/{score['n']} | {score['accuracy']:.4f} | {score['macro_f1']:.4f} |"
        )
        matrix = np.array(score["confusion_matrix"])
        ax.imshow(matrix, cmap="Blues", vmin=0, vmax=43)
        for (i, j), value in np.ndenumerate(matrix):
            ax.text(
                j,
                i,
                str(value),
                ha="center",
                va="center",
                color="white" if value > 23 else "black",
            )
        ax.set_xticks(range(3), ["Leaf spot", "Rust", "Healthy"], rotation=25)
        ax.set_yticks(range(3), ["Leaf spot", "Rust", "Healthy"])
        ax.set_xlabel("Predicted class")
        ax.set_ylabel("True class")
        ax.set_title(title.replace(" + ", "\n+ "), fontsize=10)
    fig.savefig(folder / "confusion_matrices.png", dpi=150)
    plt.close(fig)
    rows += [
        "",
        "## Per-class precision and recall",
        "",
        "95% Wilson intervals in brackets. Class order follows dataset labels.",
        "",
    ]
    for name, result in evaluated.items():
        rows += [
            f"### {NAMES[name]}",
            "",
            "| Class | Support | Precision [95% CI] | Recall [95% CI] |",
            "|---|---:|---|---|",
        ]
        for label, values in result["per_class"].items():
            p, r = values["precision_95ci"], values["recall_95ci"]
            rows.append(
                f"| {label} | {values['support']} | {values['precision']:.3f} [{p[0]:.3f}, {p[1]:.3f}] | {values['recall']:.3f} [{r[0]:.3f}, {r[1]:.3f}] |"
            )
        rows.append("")
    write_json(folder / "evaluation.json", evaluated)
    (folder / "RESULTS.md").write_text("\n".join(rows) + "\n")
    images = sorted((folder / "failure_images").glob("*.png"))[:8]
    if images:
        fig, axes = plt.subplots(2, 4, figsize=(12, 6.5), layout="constrained")
        for ax in axes.flat:
            ax.axis("off")
        for ax, path in zip(axes.flat, images):
            index = int(path.stem.split("-")[1])
            pred = predictions["resnet18_frozen"]["predicted"][index]
            ax.imshow(Image.open(path))
            ax.set_title(
                f"test:{index:04d}\nTrue: {CLASSES[truth[index]]}\nPred: {CLASSES[pred]}",
                fontsize=8,
            )
        fig.suptitle(
            "Frozen model failures: first eight errors in official test order", fontsize=13
        )
        fig.savefig(folder / "failure_examples.png", dpi=150)
        plt.close(fig)
    arrays = np.load(folder / "gradcam_arrays.npz")
    fig, axes = plt.subplots(
        len(arrays["indices"]), 2, figsize=(7, 9), squeeze=False, layout="constrained"
    )
    for row, index in enumerate(arrays["indices"]):
        rgb, heat = arrays["rgb"][row], arrays["heat"][row]
        axes[row, 0].imshow(rgb)
        axes[row, 1].imshow(rgb)
        axes[row, 1].imshow(heat, cmap="jet", alpha=0.45, vmin=0, vmax=1)
        pred = predictions["resnet18_frozen"]["predicted"][index]
        axes[row, 0].set_title(f"test:{index:04d}, true: {CLASSES[truth[index]]}", fontsize=9)
        axes[row, 1].set_title(f"Grad-CAM for predicted {CLASSES[pred]}", fontsize=9)
        for ax in axes[row]:
            ax.axis("off")
    fig.suptitle("Frozen classifier Grad-CAM, explanatory not causal", fontsize=12)
    fig.savefig(folder / "gradcam_panels.png", dpi=130)
    plt.close(fig)
    print((folder / "RESULTS.md").read_text())


if __name__ == "__main__":
    main()
